"""Machine-readable asset schema tree for MB01.

Families -> groups -> parts, every connection port, the port-joint compatibility
rules, the module catalog and hangar panel grammar, material roles and the
game-ready (collision / LOD / UV) policy - all derived from the generators and
contracts themselves, never typed by hand, so it cannot drift from the code.

Pure Python: `python -m mb01_military_studio.schema` writes docs/ASSET_SCHEMA.json.
"""
from dataclasses import asdict
from pathlib import Path
import json
from . import core, materials
from .assembly import contracts as AC
from .game_ready import ue5, building_bundle, bundle as kit
from .hangar_studio import contracts as HC
from .modular import catalog as MC, contracts as MCON

SCHEMA = 'mb01.asset_schema/0.1'
DOCS = Path(__file__).resolve().parent / 'docs' / 'ASSET_SCHEMA.json'

# Mirrors blender_backend.BuildJob / hangar_studio.blender_tools / modular.blender_tools.
COLLISION_BY_GROUP = {'DOOR': 'HULLS', 'GROUND': 'COMPLEX', 'BODY': 'COMPLEX', 'STRUCTURE': 'COMPLEX', 'ROOF': 'COMPLEX'}
# Mirrors assembly.blender_qa.port_from_object.
PROFILE_BY_ROLE = {'PEDESTRIAN': 'walkway-v1', 'PEDESTRIAN_OPENING': 'walkway-v1',
                   'HANGAR': 'aircraft-surface-v1', 'APRON': 'aircraft-surface-v1',
                   'SERVICE_ROAD': 'aircraft-surface-v1', 'FACADE': 'facade-v1'}
# Campus systems referenced by the generators' ports/notes; they are not generated by MB01.
EXTERNAL_SYSTEMS = {
    'SW01': dict(title='Walkway network', role='PEDESTRIAN', profile='walkway-v1', note='Joins PERSONNEL_* ports of equal width.'),
    'AF01': dict(title='Shared apron / taxi surface', role='APRON', profile='aircraft-surface-v1', note='Joins AIRCRAFT_IN hangar ports; disable local_ground to avoid a double floor.'),
    'PK01': dict(title='Port metadata convention', role='*', profile='*', note='pk01_width / pk01_height / pk01_role custom properties on port Empties.'),
}


def _part_record(part, model, boxes):
    return dict(name=part.name, group=part.group, primitives=part.primitive_count,
                triangles_raw=sum(max(0, len(f) - 2) for f in part.faces), vertices=len(part.vertices),
                materials=list(part.material_names), bevel_m=part.bevel,
                collision=COLLISION_BY_GROUP.get(part.group, 'NONE'), collision_boxes=len(boxes.get(part.name, [])),
                door=next((d['kind'] for d in model.doors if d['part'] == part.name), None),
                lod1=building_bundle._include(part, 1), lod2=building_bundle._include(part, 2))


def _family(kind):
    settings = core.settings_for(kind)
    model = core.build(settings)
    boxes = {}
    for c in model.collisions:
        boxes.setdefault(c['part'], []).append(c)
    groups = {}
    for p in model.parts:
        groups.setdefault(p.group, []).append(_part_record(p, model, boxes))
    ports = [dict(name=p['name'], role=p['role'], width_m=p['width'], surface_height_m=p['height'],
                  location_m=[round(x, 3) for x in p['location']], yaw_rad=round(p['yaw'], 4),
                  location_convention=p['location_convention'], profile=PROFILE_BY_ROLE[p['role']]) for p in model.ports]
    return dict(kind=kind, label=core.PRESETS[kind], defaults=asdict(settings),
                part_count=len(model.parts), triangles_raw=sum(sum(max(0, len(f) - 2) for f in p.faces) for p in model.parts),
                groups={g: parts for g, parts in sorted(groups.items())},
                ports=ports, doors=[dict(part=d['part'], kind=d['kind']) for d in model.doors],
                openings=len(model.openings), labels=[l['body'] for l in model.labels], notes=list(model.notes))


def _joint(a, b):
    """Static compatibility of two typed ports, same rules as assembly.contracts.inspect_joint
    minus the placement checks (gap/facing), which only exist once both roots are placed."""
    issues = []
    if 'PEDESTRIAN_OPENING' in (a['role'], b['role']):
        issues.append('LANDING_ADAPTER_REQUIRED')
    elif not (a['role'] == b['role'] or {a['role'], b['role']} == {'HANGAR', 'APRON'}):
        issues.append('ROLE_MISMATCH')
    if a['profile'] != b['profile']:
        issues.append('PROFILE_MISMATCH')
    if abs(a['width_m'] - b['width_m']) > AC.Tolerances().dimension_m:
        issues.append('WIDTH_MISMATCH')
    return issues


def _compatibility(families):
    nodes = [dict(id=f'{fam["kind"]}.{p["name"]}', family=fam['kind'], **p) for fam in families for p in fam['ports']]
    for key, ext in EXTERNAL_SYSTEMS.items():
        if ext['role'] != '*':
            nodes.append(dict(id=key, family=key, name=key, role=ext['role'], profile=ext['profile'], width_m=None, external=True))
    edges = []
    for i, a in enumerate(nodes):
        for b in nodes[i + 1:]:
            if a.get('external') and b.get('external'):
                continue
            aa = dict(a);bb = dict(b)
            if aa['width_m'] is None:aa['width_m'] = bb['width_m']
            if bb['width_m'] is None:bb['width_m'] = aa['width_m']
            issues = _joint(aa, bb)
            edges.append(dict(a=a['id'], b=b['id'], compatible=not issues, issues=issues))
    return dict(nodes=nodes, edges=edges,
                rules=dict(roles=['PEDESTRIAN', 'PEDESTRIAN_OPENING', 'APRON', 'HANGAR', 'SERVICE_ROAD', 'FACADE'],
                           role_rule='equal roles, or HANGAR<->APRON; PEDESTRIAN_OPENING always needs a landing adapter',
                           profile_rule='profiles must match exactly', tolerances=asdict(AC.Tolerances()),
                           placement_rule='direct butt joint only: surface gap, facing and up-vector within tolerance; no path routing',
                           source='assembly.contracts.inspect_joint'))


def _hangar_studio():
    presets = {}
    for pid in HC.PRESETS:
        c = HC.preset(pid)
        presets[pid] = dict(name=c.name, width=c.width, depth=c.depth, bays=c.bays, roof_type=c.roof_type,
                            gate_leaves=c.gate_leaves, left=list(c.panel_sequence('LEFT')), right=list(c.panel_sequence('RIGHT')))
    return dict(panel_types=list(HC.PANEL_TYPES), entry_types=sorted(HC.ENTRY_TYPES), panel_modules=dict(HC.PANEL_MODULES),
                numeric_ranges={n: [lo, hi] for n, lo, hi in HC.NUMERIC_RANGES},
                grammar=['one panel token per bay, per side (LEFT/RIGHT); bays 4..12',
                         'depth / bays (bay pitch) must be 2.8..6 m',
                         'two ENTRY_TYPES panels may not be adjacent',
                         'with local_ground+landings an entry bay needs pitch >= walkway_width + .12 m',
                         'default sequence: CLERESTORY everywhere, METAL first, LOUVER last, PERSONNEL in bay 2 (LEFT) / bays-1 (RIGHT)',
                         'main gate: 4/6/8 telescopic leaves; side pocket >= leaf + .25 m; opening_height + .95 <= eave_height'],
                presets=presets)


def _modular():
    cat = MC.catalog()
    modules = [dict(id=m.id, title=m.title, category=m.category, families=list(m.families), status=m.status,
                    width_range=list(m.width_range), height_range=list(m.height_range),
                    default_width=m.default_width, default_height=m.default_height, builder=m.builder, note=m.note)
               for m in cat.values()]
    return dict(families=list(MCON.FAMILIES), modules=modules,
                implemented=sum(1 for m in modules if m['status'] == 'implemented_core'), planned=sum(1 for m in modules if m['status'] != 'implemented_core'),
                style_roles=dict(palette=['COASTAL', 'WOODLAND', 'URBAN'], wall=['Plaster', 'Concrete', 'ConcreteLight'],
                                 frame=['SteelDark', 'RoofOlive', 'Galvanized'], plinth=['Stone', 'Concrete', 'ConcreteLight']),
                facade_rules=['1..32 cells, each module allowed only in its listed families',
                              'cell width within the module width_range; height within height_range; thickness .16..0.50 m',
                              'cells are laid along -Y from +total/2; nothing is scaled to hit target_width - a mismatch is an error',
                              'single-storey straight strip; no corner/closure modules exist yet'],
                game_kit_modules=list(kit.NEW_MODULES))


def _materials():
    recipe = materials.recipes()
    res = materials.resolution_report(recipe)
    return dict(roles={k: dict(texture_family=v[0], tint=list(v[1]), roughness=v[2], metallic=v[3], tile_m=v[4]) for k, v in materials.SPECS.items()},
                texture_families={tag: dict(resolution=info['sizes']['BaseColor'][0], maps=sorted(info['sizes']))
                                  for tag, info in res['families'].items()},
                resolution_unified=res['unified'], maps_per_family=['BaseColor', 'ORM', 'NormalGL', 'NormalDX', 'Height'],
                blender_shader='NormalGL + Height bump + object-space grunge (wear)', unreal_material='NormalDX preferred, green flip for GL')


def build_schema():
    families = [_family(k) for k in core.PRESETS]
    groups = {}
    for fam in families:
        for g, parts in fam['groups'].items():
            rec = groups.setdefault(g, dict(parts=0, families=set(), collision=COLLISION_BY_GROUP.get(g, 'NONE'),
                                            lod1='kept' if g != 'PROPS' else 'dropped', lod2='kept' if g in building_bundle._MAJOR else 'dropped'))
            rec['parts'] += len(parts);rec['families'].add(fam['kind'])
    for rec in groups.values():
        rec['families'] = sorted(rec['families'])
    return dict(schema=SCHEMA, generator=core.VERSION,
                families=families, groups=groups, compatibility=_compatibility(families),
                external_systems=EXTERNAL_SYSTEMS, hangar_studio=_hangar_studio(), modular=_modular(), materials=_materials(),
                game_ready=dict(lod=dict(min_lod0_triangles=ue5.LOD_MIN_TRIANGLES, lod1='primitives without edge bevel',
                                         lod2=f'LOD1 collapsed to {ue5.LOD2_COLLAPSE_RATIO:.0%} when smaller',
                                         whole_building='semantic LOD0/1/2 via game_ready.building_bundle'),
                                collision=dict(ucx_max_hulls=ue5.UCX_MAX_HULLS, hulls='generator collision boxes -> UCX_ per primitive',
                                               fallback='complex-as-simple', doors='one hinge-local hull'),
                                uv=dict(uv0='UV0_Tile, 1 unit = 1 m, repeating', uv1=ue5.LIGHTMAP_UV + ' unique 0..1 shelf-packed coplanar islands'),
                                naming=dict(mesh='SM_MB01_<Part>', collision='UCX_<asset>_NN', lod='<asset>_LOD<n>.fbx', signage='MB01_LABEL_*'),
                                engine='Unreal Engine 5 via unreal/MB01_Import.py (FBX, -Y forward, Z up, metres)'))


def write_schema(path=DOCS):
    data = build_schema()
    Path(path).write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding='utf-8')
    return path, data


if __name__ == '__main__':
    path, data = write_schema()
    print(path, '-', len(data['families']), 'families,', len(data['groups']), 'groups,', len(data['compatibility']['edges']), 'port pairs')
